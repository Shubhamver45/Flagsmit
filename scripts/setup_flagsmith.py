import os
import sys
import time
import json
import secrets
import requests

def setup_django_shell():
    """
    Executed ONLY inside Django shell (python manage.py shell).
    Creates ONLY the core primitives that require direct DB access:
    1. Admin user
    2. Organisation
    3. Project
    4. Environment
    5. Master API Key
    6. Warehouse connection (for SDK event storage)
    
    All feature flags, variants, metrics, and experiments are created
    strictly through the public Admin API as per official documentation.
    """
    admin_email = os.environ.get("ADMIN_EMAIL", "admin@example.com")
    admin_password = os.environ.get("ADMIN_PASSWORD")
    if not admin_password:
        admin_password = secrets.token_urlsafe(16)

    webhook_secret = os.environ.get("FLAGSMITH_WEBHOOK_SECRET")
    if not webhook_secret:
        webhook_secret = secrets.token_hex(16)

    from users.models import FFAdminUser
    from organisations.models import Organisation, OrganisationRole, UserOrganisation
    from projects.models import Project
    from environments.models import Environment
    from api_keys.models import MasterAPIKey
    from experimentation.models import WarehouseConnection, WarehouseType, WarehouseConnectionStatus
    from experimentation.views import verify_warehouse_connection

    # 1. Admin User
    user, created = FFAdminUser.objects.get_or_create(
        email=admin_email,
        defaults={
            "first_name": "Admin",
            "last_name": "Guardian",
            "is_staff": True,
            "is_superuser": True,
        }
    )
    user.set_password(admin_password)
    user.is_staff = True
    user.is_superuser = True
    user.save()
    if not created:
        print(f"User: {user.email} (existing user updated with ADMIN_PASSWORD from .env)")
    else:
        print(f"User: {user.email} (created: {created})")

    # 2. Organisation
    org, created = Organisation.objects.get_or_create(
        name="Guardian Org",
    )
    UserOrganisation.objects.get_or_create(
        user=user,
        organisation=org,
        defaults={"role": OrganisationRole.ADMIN.name}
    )
    print(f"Organisation: {org.name} [ID={org.id}]")

    # 3. Project
    project, created = Project.objects.get_or_create(
        name="Guardian Project",
        organisation=org
    )
    print(f"Project: {project.name} [ID={project.id}]")

    # 4. Environment
    env, created = Environment.objects.get_or_create(
        name="Development",
        project=project
    )
    print(f"Environment: {env.name} [ID={env.id}, Key={env.api_key}]")

    # 5. Master Admin API Key & Ops Engineer API Key
    MasterAPIKey.objects.filter(organisation=org, name="Guardian Admin Key").delete()
    key_obj, raw_key = MasterAPIKey.objects.create_key(
        name="Guardian Admin Key",
        organisation=org,
        is_admin=True
    )
    print(f"Admin API Key Prefix: {key_obj.prefix}")
    print("Admin API Key: written to .env")

    MasterAPIKey.objects.filter(organisation=org, name="ops-engineer").delete()
    ops_key_obj, raw_ops_key = MasterAPIKey.objects.create_key(
        name="ops-engineer",
        organisation=org,
        is_admin=True
    )
    print(f"Ops API Key Prefix: {ops_key_obj.prefix}")
    print("Ops API Key: written to .env")

    # 6. Warehouse Connection (Flagsmith Database for SDK event collection)
    wh_conn, created = WarehouseConnection.objects.get_or_create(
        environment=env,
        defaults={
            "name": f"Flagsmith Database - {env.name}",
            "warehouse_type": WarehouseType.POSTGRES.value,
            "config": {"source": "flagsmith_database"},
            "credentials": {},
            "status": WarehouseConnectionStatus.CREATED,
        }
    )
    wh_conn.warehouse_type = WarehouseType.POSTGRES.value
    wh_conn.config = {"source": "flagsmith_database"}
    wh_conn.credentials = {}
    wh_conn.save()

    print(f"Verifying Flagsmith Database Warehouse connection for environment '{env.name}'...")
    verify_warehouse_connection(wh_conn, persist=True)
    wh_conn.refresh_from_db()
    print(f"Warehouse Connection Status: {wh_conn.status} (detail: {wh_conn.status_detail})")

    if wh_conn.status != WarehouseConnectionStatus.CONNECTED:
        print(f"ERROR: Warehouse connection is not CONNECTED: {wh_conn.status_detail}", file=sys.stderr)
        sys.exit(1)

    # Clean historical SDK events to prevent identity cross-experiment quarantine
    from experimentation.models import SDKExperimentationEvent
    SDKExperimentationEvent.objects.filter(environment_key=env.api_key).delete()

    # 7. Generate .env file contents
    dotenv_content = f"""# Flagsmith API Configuration (Auto-generated by scripts/setup_flagsmith.py)
FLAGSMITH_URL=http://localhost:8000/api/v1
FLAGSMITH_ADMIN_API_KEY={raw_key}
FLAGSMITH_OPS_API_KEY={raw_ops_key}
FLAGSMITH_ENVIRONMENT_KEY={env.api_key}
FLAGSMITH_ORG_ID={org.id}
FLAGSMITH_PROJECT_ID={project.id}
FLAGSMITH_ENVIRONMENT_ID={env.id}

# Flagsmith Webhook Secret (HMAC-SHA256 signature verification)
FLAGSMITH_WEBHOOK_SECRET={webhook_secret}

# Flagsmith Experimentation Recalculation (Optional, DEMO_FORCE_RECALC=1 for fast demo testing)
# DEMO_FORCE_RECALC=1

# Initial Flagsmith Admin Credentials (for setup)
ADMIN_EMAIL={admin_email}
ADMIN_PASSWORD={admin_password}

# Guardian API Authentication (Optional for local dev, recommended for production)
# GUARDIAN_API_TOKEN=

# Demo App Authentication (Optional, protects /toggle-bug and /reset-metrics)
# DEMO_API_TOKEN=
"""

    print("\n=== SETUP SUMMARY (CORE PRIMITIVES) ===")
    print(f"Dashboard URL: http://localhost:8000")
    print(f"Admin Login: {admin_email} (password: written to .env)")
    print(f"Organisation: {org.name} (ID: {org.id})")
    print(f"Project: {project.name} (ID: {project.id})")
    print(f"Environment: {env.name} (ID: {env.id})")
    print(f"Environment Client Key: {env.api_key}")
    print("Admin API Key: written to .env")
    print(f"Warehouse Status: {wh_conn.status}")

    # Delimited block for host extraction
    print("\n=== DOTENV_START ===")
    print(dotenv_content.strip())
    print("=== DOTENV_END ===\n")


def setup_via_admin_api(
    api_url: str,
    admin_api_key: str,
    project_id: int,
    env_id: int,
    env_key: str,
    webhook_secret: str = "",
    admin_email: str = "",
    admin_password: str = "",
):
    """
    Creates flag variants, the metric, and the experiment, and starts it,
    THROUGH THE PUBLIC ADMIN API as documented in official Flagsmith docs:
    https://docs.flagsmith.com/experimentation/set-up-with-a-coding-agent
    """
    headers = {
        "Authorization": f"Api-Key {admin_api_key}",
        "Content-Type": "application/json",
    }
    print("==> Configuring Flags, Metric, and Experiment via Public Admin API...")

    # 0. Verify Admin login via POST /api/v1/auth/login/
    if admin_email and admin_password:
        try:
            auth_resp = requests.post(
                f"{api_url}/auth/login/",
                json={"email": admin_email, "password": admin_password},
                headers={"Content-Type": "application/json"},
                timeout=5,
            )
            auth_resp.raise_for_status()
            auth_key = auth_resp.json().get("key", "")
            print(f"  ✔ Verified Admin login via POST /api/v1/auth/login/ (token received: {auth_key[:8]}...)")
        except Exception as e:
            print(f"  ⚠️ Admin login verification failed: {e}", file=sys.stderr)

    # 1. Feature: new_checkout (Multivariate Rollout Flag)
    feats_resp = requests.get(f"{api_url}/projects/{project_id}/features/", headers=headers)
    feats_resp.raise_for_status()
    feats = feats_resp.json().get("results", [])
    nc_feat = next((f for f in feats if f["name"] == "new_checkout"), None)
    if nc_feat and nc_feat.get("type") != "MULTIVARIATE":
        requests.delete(f"{api_url}/projects/{project_id}/features/{nc_feat['id']}/", headers=headers)
        nc_feat = None

    if not nc_feat:
        r = requests.post(
            f"{api_url}/projects/{project_id}/features/",
            headers=headers,
            json={
                "name": "new_checkout",
                "type": "MULTIVARIATE",
                "default_enabled": False,
                "initial_value": "old_flow",
                "description": "New checkout flow gated rollout flag",
                "multivariate_options": [
                    {
                        "type": "unicode",
                        "string_value": "new_flow",
                        "default_percentage_allocation": 0.0,
                    }
                ],
            },
        )
        r.raise_for_status()
        nc_feat = r.json()
        print(f"  ✔ Created multivariate feature 'new_checkout' via Admin API (ID={nc_feat['id']})")
    else:
        print(f"  ✔ Multivariate feature 'new_checkout' already exists via Admin API (ID={nc_feat['id']})")

    # 2. Multivariate Feature: checkout_experiment
    exp_feat = next((f for f in feats if f["name"] == "checkout_experiment"), None)
    if not exp_feat:
        r = requests.post(
            f"{api_url}/projects/{project_id}/features/",
            headers=headers,
            json={
                "name": "checkout_experiment",
                "type": "MULTIVARIATE",
                "initial_value": "control",
                "default_enabled": True,
                "description": "Multivariate feature flag for checkout A/B experiment",
                "multivariate_options": [
                    {
                        "type": "unicode",
                        "string_value": "variation",
                        "default_percentage_allocation": 50.0,
                        "key": "variation",
                    }
                ],
            },
        )
        r.raise_for_status()
        exp_feat = r.json()
        print(f"  ✔ Created multivariate feature 'checkout_experiment' via Admin API (ID={exp_feat['id']})")
    else:
        print(f"  ✔ Multivariate feature 'checkout_experiment' already exists via Admin API (ID={exp_feat['id']})")

    mv_options = exp_feat.get("multivariate_options", [])
    if not mv_options:
        f_detail = requests.get(f"{api_url}/projects/{project_id}/features/{exp_feat['id']}/", headers=headers).json()
        mv_options = f_detail.get("multivariate_options", [])
    opt_id = mv_options[0]["id"]

    # Flagsmith's nested feature serializer marks 'key' as read-only on feature create.
    # Set the variant key on the dedicated mv-options endpoint so Flagsmith computes SRM:
    requests.patch(
        f"{api_url}/projects/{project_id}/features/{exp_feat['id']}/mv-options/{opt_id}/",
        headers=headers,
        json={"key": "variation", "feature": exp_feat["id"], "default_percentage_allocation": 50.0},
    ).raise_for_status()

    # 3. Clean up any existing experiments & metrics for a reproducible fresh run
    exps_resp = requests.get(f"{api_url}/environments/{env_key}/experiments/", headers=headers)
    exps = exps_resp.json().get("results", []) if exps_resp.status_code == 200 else []
    for exp in exps:
        if exp["status"] == "running":
            requests.post(f"{api_url}/environments/{env_key}/experiments/{exp['id']}/complete/", headers=headers)
        requests.delete(f"{api_url}/environments/{env_key}/experiments/{exp['id']}/", headers=headers)
        print(f"  ✔ Reset existing experiment {exp['id']} via Admin API")

    metrics_resp = requests.get(f"{api_url}/environments/{env_key}/experiment-metrics/", headers=headers)
    metrics = metrics_resp.json().get("results", []) if metrics_resp.status_code == 200 else []
    for m in metrics:
        requests.delete(f"{api_url}/environments/{env_key}/experiment-metrics/{m['id']}/", headers=headers)
        print(f"  ✔ Reset existing metric {m['id']} via Admin API")

    # 4. Conversion Metric: Checkout Completed
    m_res = requests.post(
        f"{api_url}/environments/{env_key}/experiment-metrics/",
        headers=headers,
        json={
            "name": "Checkout Completed",
            "description": "Conversion metric tracking completed checkout purchases",
            "aggregation": "count",
            "direction": "up",
            "definition": {"version": 1, "event": "checkout_completed"},
        },
    )
    m_res.raise_for_status()
    metric_id = m_res.json()["id"]
    print(f"  ✔ Created metric 'Checkout Completed' via Admin API (ID={metric_id})")

    # 5. Create Experiment: Checkout A/B Experiment
    exp_res = requests.post(
        f"{api_url}/environments/{env_key}/experiments/",
        headers=headers,
        json={
            "feature": exp_feat["id"],
            "name": "Checkout A/B Experiment",
            "hypothesis": "New checkout flow increases completed checkouts without increasing errors",
            "metrics": [{"metric": metric_id, "expected_direction": "increase"}],
            "experiment_rollout": {
                "enabled": True,
                "rollout_percentage": 100.0,
                "feature_state_value": {"type": "string", "value": "control"},
                "multivariate_feature_state_values": [
                    {
                        "multivariate_feature_option": opt_id,
                        "percentage_allocation": 50.0,
                    }
                ],
            },
        },
    )
    exp_res.raise_for_status()
    exp_data = exp_res.json()
    exp_id = exp_data["id"]
    print(f"  ✔ Created experiment '{exp_data['name']}' via Admin API (ID={exp_id})")

    # 6. Start Experiment
    start_res = requests.post(f"{api_url}/environments/{env_key}/experiments/{exp_id}/start/", headers=headers)
    start_res.raise_for_status()
    started_data = start_res.json()
    print(f"  ✔ Started experiment via Admin API (status={started_data.get('status')})")

    # 7. Configure base environment feature state to 50% allocation on variation for SRM expected shares
    fs_resp = requests.get(f"{api_url}/features/featurestates/?environment={env_id}&feature={exp_feat['id']}", headers=headers)
    if fs_resp.status_code == 200:
        env_fs = next((f for f in fs_resp.json().get("results", []) if f.get("feature_segment") is None), None)
        if env_fs and env_fs.get("multivariate_feature_state_values"):
            mv_val = env_fs["multivariate_feature_state_values"][0]
            requests.patch(
                f"{api_url}/features/featurestates/{env_fs['id']}/",
                headers=headers,
                json={
                    "environment": env_id,
                    "multivariate_feature_state_values": [
                        {
                            "id": mv_val["id"],
                            "multivariate_feature_option": opt_id,
                            "percentage_allocation": 50.0,
                        }
                    ],
                },
            )
            print("  ✔ Configured 50/50 variant allocation on environment feature state via Admin API")

    # 6. Environment Webhook for Guardian Real-Time Drift Detection
    if webhook_secret:
        webhook_url = os.environ.get("GUARDIAN_WEBHOOK_URL", "http://host.docker.internal:8080/webhooks/flagsmith")
        try:
            wh_get = requests.get(f"{api_url}/environments/{env_key}/webhooks/", headers=headers)
            wh_get.raise_for_status()
            existing_webhooks = wh_get.json() if wh_get.status_code == 200 else []
            match = next((w for w in existing_webhooks if w.get("url") == webhook_url), None)
            if not match:
                wh_post = requests.post(
                    f"{api_url}/environments/{env_key}/webhooks/",
                    headers=headers,
                    json={
                        "url": webhook_url,
                        "secret": webhook_secret,
                        "enabled": True,
                    },
                )
                wh_post.raise_for_status()
                print(f"  ✔ Registered Guardian environment webhook via Admin API ({webhook_url})")
            else:
                requests.patch(
                    f"{api_url}/environments/{env_key}/webhooks/{match['id']}/",
                    headers=headers,
                    json={"secret": webhook_secret, "enabled": True},
                ).raise_for_status()
                print(f"  ✔ Verified Guardian environment webhook via Admin API ({webhook_url}, ID={match['id']})")
        except Exception as e:
            print(f"  ⚠️ Could not auto-register Guardian webhook: {e}", file=sys.stderr)


def host_run():
    """Wrapper executed when setup_flagsmith.py is called from host."""
    import subprocess
    import secrets
    from pathlib import Path

    root_dir = Path(__file__).resolve().parent.parent
    script_path = root_dir / "scripts" / "setup_flagsmith.py"
    env_file = root_dir / ".env"

    admin_password = os.environ.get("ADMIN_PASSWORD")
    if not admin_password:
        admin_password = secrets.token_urlsafe(16)

    print("==> Copying setup script into Flagsmith container...")
    subprocess.run(["docker", "compose", "cp", str(script_path), "flagsmith:/app/setup_flagsmith.py"], check=True)

    print("==> Executing core DB setup inside Flagsmith Django shell (admin user, org, project, env, master key)...")
    try:
        proc = subprocess.run(
            [
                "docker", "compose", "exec", "-T",
                "-e", f"ADMIN_PASSWORD={admin_password}",
                "flagsmith", "python", "manage.py", "shell",
                "-c", "exec(open('/app/setup_flagsmith.py').read()); setup_django_shell()"
            ],
            capture_output=True,
            text=True,
            check=True,
        )
    except subprocess.CalledProcessError as e:
        print("Setup inside Flagsmith failed!", file=sys.stderr)
        if e.stdout:
            print("--- STDOUT ---", file=sys.stderr)
            print(e.stdout, file=sys.stderr)
        if e.stderr:
            print("--- STDERR ---", file=sys.stderr)
            print(e.stderr, file=sys.stderr)
        raise

    if "=== DOTENV_START ===" in proc.stdout:
        before, rest = proc.stdout.split("=== DOTENV_START ===", 1)
        dotenv, after = rest.split("=== DOTENV_END ===", 1)
        dotenv = dotenv.strip()
        cleaned_stdout = before.rstrip() + ("\n" + after.lstrip() if after.strip() else "")

        existing_slack = ""
        if env_file.exists():
            for line in env_file.read_text(encoding="utf-8").splitlines():
                if line.startswith("SLACK_WEBHOOK_URL="):
                    existing_slack = line.strip()
        if existing_slack:
            dotenv += f"\n{existing_slack}\n"
        else:
            dotenv += "\n# Webhooks (Optional)\nSLACK_WEBHOOK_URL=\n"
        with open(env_file, "w", encoding="utf-8") as f:
            f.write(dotenv + "\n")

        print(cleaned_stdout.strip())
        print(f"✔ Admin API key and password written to {env_file}")
    else:
        print(proc.stdout.strip())

    if proc.stderr:
        print(proc.stderr, file=sys.stderr)

    # Now execute step 2: Public Admin API configuration for features, metric, and experiment
    from dotenv import dotenv_values
    conf = dotenv_values(env_file)
    api_url = conf.get("FLAGSMITH_URL", "http://localhost:8000/api/v1")
    admin_key = conf.get("FLAGSMITH_ADMIN_API_KEY", "")
    proj_id = int(conf.get("FLAGSMITH_PROJECT_ID", "1"))
    env_id = int(conf.get("FLAGSMITH_ENVIRONMENT_ID", "1"))
    env_key = conf.get("FLAGSMITH_ENVIRONMENT_KEY", "")

    webhook_secret = conf.get("FLAGSMITH_WEBHOOK_SECRET", "")
    admin_email = conf.get("ADMIN_EMAIL", "admin@example.com")
    admin_password = conf.get("ADMIN_PASSWORD", "")

    setup_via_admin_api(
        api_url,
        admin_key,
        proj_id,
        env_id,
        env_key,
        webhook_secret=webhook_secret,
        admin_email=admin_email,
        admin_password=admin_password,
    )


if __name__ == "__main__":
    try:
        import django
        # Running inside container
        setup_django_shell()
    except ImportError:
        # Running on host
        host_run()
